// Real-browser regression check for the RCC folder picker's layout.
//
// jsdom has no layout engine, so the jest suite can only pin the picker's
// SELECTION contract. The bug this script exists for was invisible there: a
// real mouse click focuses react-checkbox-tree's visually hidden native
// checkbox, and Chrome then scrolls the nearest scrollable ancestor to reveal
// it. That ancestor used to be MUI's Dialog Paper, which carried the tree and
// the action row thousands of pixels above the dialog and left the white
// space the curators reported.
//
// Usage (Chrome must be installed; nothing is added to package.json):
//
//   yarn next dev -p 3311
//   node scripts/filetree-layout-probe.mjs            # measurements only
//   node scripts/filetree-layout-probe.mjs --shots out # + PNGs per viewport
//
// It writes a temporary probe page under pages/, drives Chrome over CDP with
// no dependencies (Node 22+ ships a global WebSocket), and removes the page
// again on the way out. Exit code 1 means the layout moved.
import { spawn } from "node:child_process";
import { mkdtempSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PAGE = join(HERE, "..", "pages", "__filetree-layout-probe.js");
const PORT = process.env.PROBE_PORT || "3311";
const SHOTS = process.argv.includes("--shots")
  ? process.argv[process.argv.indexOf("--shots") + 1] || "filetree"
  : null;

const CHROME_CANDIDATES = [
  process.env.CHROME_PATH,
  "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
  "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
  "/usr/bin/google-chrome",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
].filter(Boolean);

// Four viewports, including the one the reported screenshots came from.
const VIEWPORTS = [
  { name: "1920x1080", width: 1920, height: 1080 },
  { name: "1440x900", width: 1440, height: 900 },
  { name: "900x800", width: 900, height: 800 },
  { name: "390x844", width: 390, height: 844 },
];

// A row may move by at most this much when it is ticked.
const TOLERANCE = 4;

const PROBE_PAGE = `// Generated by scripts/filetree-layout-probe.mjs. Safe to delete.
import { useContext, useEffect } from "react";

import FileTree from "../components/FileTree";
import SourceTreeState from "../Context/SourceTree/SourceTreeState";
import SourceTreeContext from "../Context/SourceTree/SourceTreeContext";
import CuratorContext from "../Context/Curator/curatorContext";

// An RCC-shaped listing: one parent whose children are already loaded, then
// 180 siblings with long unbroken names.
const NODES = [
  {
    label: "10.1021.acs.jctc.9b00999_parent_with_loaded_children",
    value: "/files/10.1021.acs.jctc.9b00999",
    children: [
      { label: "figures_tables", value: "/files/10.1021.acs.jctc.9b00999/figures_tables", children: [] },
      { label: "data", value: "/files/10.1021.acs.jctc.9b00999/data", children: [] },
      { label: "scripts", value: "/files/10.1021.acs.jctc.9b00999/scripts", children: [] },
    ],
  },
  ...Array.from({ length: 180 }, (unused, index) => ({
    label: \`10.1021.acs.jctc.\${5 + (index % 5)}c0\${1000 + index}_espresso_calculation_directory_with_a_long_unbroken_name_\${index}\`,
    value: \`/files/10.1021.acs.jctc.\${5 + (index % 5)}c0\${1000 + index}\`,
    children: [],
  })),
];

const Opener = () => {
  const { setTree, openSelector, setMultiple, setSaveMethod, setConfirmLabel } =
    useContext(SourceTreeContext);

  useEffect(() => {
    setTree(NODES);
    setMultiple(false);
    setSaveMethod((value) => {
      window.__saved = (window.__saved || []).concat(value);
    });
    setConfirmLabel("Use");
    openSelector();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // A tall page behind the dialog: the backdrop must not scroll either.
  return <div id="probe-ready" style={{ height: "300vh" }} />;
};

export default function FileTreeLayoutProbe() {
  return (
    <CuratorContext.Provider value={{ fileServerPath: "" }}>
      <SourceTreeState>
        <Opener />
        <FileTree />
      </SourceTreeState>
    </CuratorContext.Provider>
  );
}
`;

const MEASURE = `(() => {
  const box = (el) => {
    if (!el) return null;
    const r = el.getBoundingClientRect();
    return { top: +r.top.toFixed(1), bottom: +r.bottom.toFixed(1),
             left: +r.left.toFixed(1), h: +r.height.toFixed(1),
             w: +r.width.toFixed(1) };
  };
  const paper = document.querySelector(".MuiDialog-paper");
  const content = document.querySelector(".MuiDialogContent-root");
  const actions = document.querySelector(".MuiDialogActions-root");
  const active = document.activeElement;
  const row = window.__probeRow || null;
  return JSON.stringify({
    paper: box(paper),
    paperDisplay: paper ? getComputedStyle(paper).display : null,
    content: box(content),
    actions: box(actions),
    contentClientH: content ? content.clientHeight : null,
    contentScrollH: content ? content.scrollHeight : null,
    contentScrollTop: content ? content.scrollTop : null,
    contentOverflowX: content ? content.scrollWidth - content.clientWidth : null,
    paperScrollTop: paper ? paper.scrollTop : null,
    windowScrollY: window.scrollY,
    rowTop: row ? +row.getBoundingClientRect().top.toFixed(1) : null,
    active: active ? { tag: active.tagName, type: active.type || "" } : null,
    gapBelowActions: (paper && actions)
      ? +(paper.getBoundingClientRect().bottom - actions.getBoundingClientRect().bottom).toFixed(1)
      : null,
    actionsInsidePaper: (paper && actions)
      ? actions.getBoundingClientRect().bottom <= paper.getBoundingClientRect().bottom + 1 &&
        actions.getBoundingClientRect().top >= paper.getBoundingClientRect().top
      : false,
    actionsOnScreen: actions
      ? actions.getBoundingClientRect().top >= 0 &&
        actions.getBoundingClientRect().bottom <= window.innerHeight
      : false,
    checkedRows: document.querySelectorAll(".rct-icon-check").length,
    useDisabled: (() => {
      const b = Array.from(document.querySelectorAll(".MuiDialogActions-root button"))
        .find((x) => /^use$/i.test((x.textContent || "").trim()));
      return b ? b.disabled : null;
    })(),
  });
})()`;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const chromeBinary = () => {
  for (const path of CHROME_CANDIDATES) {
    if (existsSync(path)) return path;
  }
  throw new Error(
    `Chrome not found. Set CHROME_PATH. Tried: ${CHROME_CANDIDATES.join(", ")}`
  );
};

const waitForRoute = async (url) => {
  for (let i = 0; i < 90; i += 1) {
    try {
      const response = await fetch(url);
      if (response.ok) return;
    } catch { /* dev server still compiling */ }
    await sleep(1000);
  }
  throw new Error(`${url} never became available — is \`next dev\` running?`);
};

const main = async () => {
  writeFileSync(PAGE, PROBE_PAGE);
  const url = `http://localhost:${PORT}/__filetree-layout-probe`;
  await waitForRoute(url);

  const profile = mkdtempSync(join(tmpdir(), "filetree-probe-"));
  const chrome = spawn(chromeBinary(), [
    "--headless=new", "--remote-debugging-port=9340",
    `--user-data-dir=${profile}`, "--no-first-run", "--disable-gpu",
    "about:blank",
  ]);

  let ws;
  const failures = [];
  try {
    let debuggerUrl = null;
    for (let i = 0; i < 90 && !debuggerUrl; i += 1) {
      try {
        const response = await fetch("http://127.0.0.1:9340/json/version");
        debuggerUrl = (await response.json()).webSocketDebuggerUrl;
      } catch { await sleep(300); }
    }
    if (!debuggerUrl) throw new Error("Chrome did not expose a debugger");

    ws = new WebSocket(debuggerUrl);
    await new Promise((resolve) => ws.addEventListener("open", resolve));
    let id = 0;
    const pending = new Map();
    ws.addEventListener("message", (event) => {
      const message = JSON.parse(event.data);
      if (message.id && pending.has(message.id)) {
        pending.get(message.id)(message.result);
        pending.delete(message.id);
      }
    });
    const send = (method, params = {}, sessionId) => {
      id += 1;
      ws.send(JSON.stringify({ id, method, params, ...(sessionId ? { sessionId } : {}) }));
      return new Promise((resolve) => pending.set(id, resolve));
    };

    const { targetId } = await send("Target.createTarget", { url: "about:blank" });
    const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
    await send("Page.enable", {}, sessionId);
    await send("Runtime.enable", {}, sessionId);

    const run = async (expression) => {
      const result = await send("Runtime.evaluate",
        { expression, returnByValue: true, awaitPromise: true }, sessionId);
      if (result.exceptionDetails) {
        throw new Error(JSON.stringify(result.exceptionDetails).slice(0, 300));
      }
      return result.result.value;
    };
    // A REAL click: it focuses what is under the pointer. `element.click()`
    // does not, and that is the entire difference between the bug reproducing
    // and not.
    const mouseClick = async (x, y) => {
      for (const type of ["mousePressed", "mouseReleased"]) {
        await send("Input.dispatchMouseEvent", {
          type, x, y, button: "left", clickCount: 1,
          buttons: type === "mousePressed" ? 1 : 0,
        }, sessionId);
        await sleep(30);
      }
    };
    const check = (viewport, label, ok, detail) => {
      if (!ok) failures.push(`${viewport}: ${label} — ${detail}`);
      return ok;
    };

    let firstLoad = true;
    for (const viewport of VIEWPORTS) {
      await send("Emulation.setDeviceMetricsOverride", {
        width: viewport.width, height: viewport.height,
        deviceScaleFactor: 1, mobile: viewport.width < 500,
      }, sessionId);
      await send("Page.navigate", { url }, sessionId);
      await sleep(firstLoad ? 8000 : 3000);
      firstLoad = false;

      // Expand a folder, scroll two thirds down, and aim at a row in the
      // middle of the tree viewport.
      await run(`(() => { const b = document.querySelector(".rct-collapse");
        if (b) b.click(); })()`);
      await sleep(400);
      await run(`(() => {
        const c = document.querySelector(".MuiDialogContent-root");
        c.scrollTop = Math.round((c.scrollHeight - c.clientHeight) * 0.66);
        const mid = c.getBoundingClientRect().top + c.clientHeight / 2;
        window.__probeRow = Array.from(document.querySelectorAll(".rct-node"))
          .find((n) => n.getBoundingClientRect().top > mid);
      })()`);
      await sleep(250);

      const before = JSON.parse(await run(MEASURE));
      const spot = JSON.parse(await run(`(() => {
        const b = window.__probeRow.querySelector(".rct-checkbox").getBoundingClientRect();
        return JSON.stringify({ x: Math.round(b.left + b.width / 2),
                                y: Math.round(b.top + b.height / 2) });
      })()`));
      await mouseClick(spot.x, spot.y);

      const atFrame = JSON.parse(await run(
        `new Promise((r) => requestAnimationFrame(() => r(${MEASURE})))`));
      if (SHOTS) {
        const shot = await send("Page.captureScreenshot", { format: "png" }, sessionId);
        writeFileSync(`${SHOTS}-${viewport.name}-checked.png`,
          Buffer.from(shot.data, "base64"));
      }
      await sleep(200);
      const after = JSON.parse(await run(MEASURE));
      if (SHOTS) {
        const shot = await send("Page.captureScreenshot", { format: "png" }, sessionId);
        writeFileSync(`${SHOTS}-${viewport.name}-after200.png`,
          Buffer.from(shot.data, "base64"));
      }

      const name = viewport.name;
      const drift = Math.abs(after.rowTop - before.rowTop);
      const frameDrift = Math.abs(atFrame.rowTop - before.rowTop);
      check(name, "row stays put", drift <= TOLERANCE && frameDrift <= TOLERANCE,
        `moved ${frameDrift}px at the next frame, ${drift}px after 200ms`);
      check(name, "tree keeps its scroll position",
        Math.abs(after.contentScrollTop - before.contentScrollTop) <= TOLERANCE,
        `${before.contentScrollTop} -> ${after.contentScrollTop}`);
      check(name, "the Paper never scrolls", after.paperScrollTop === 0,
        `paper.scrollTop = ${after.paperScrollTop}`);
      check(name, "the page behind stays still",
        after.windowScrollY === before.windowScrollY,
        `${before.windowScrollY} -> ${after.windowScrollY}`);
      check(name, "Paper keeps its box",
        JSON.stringify(after.paper) === JSON.stringify(before.paper),
        `${JSON.stringify(before.paper)} -> ${JSON.stringify(after.paper)}`);
      check(name, "the tree area keeps its height",
        after.contentClientH === before.contentClientH,
        `${before.contentClientH} -> ${after.contentClientH}`);
      check(name, "the actions keep their box",
        JSON.stringify(after.actions) === JSON.stringify(before.actions),
        `${JSON.stringify(before.actions)} -> ${JSON.stringify(after.actions)}`);
      check(name, "no empty space under the actions",
        Math.abs(after.gapBelowActions) <= 1, `${after.gapBelowActions}px`);
      check(name, "the actions stay in the dialog and on screen",
        after.actionsInsidePaper && after.actionsOnScreen,
        `insidePaper=${after.actionsInsidePaper} onScreen=${after.actionsOnScreen}`);
      check(name, "the tree does not scroll sideways",
        after.contentOverflowX <= 0, `${after.contentOverflowX}px of overflow`);
      check(name, "exactly one row is ticked", after.checkedRows === 1,
        `${after.checkedRows} ticked`);
      check(name, "Use became available", after.useDisabled === false,
        `disabled=${after.useDisabled}`);

      // A second folder must still be reachable, and it replaces the first.
      const second = JSON.parse(await run(`(() => {
        const c = document.querySelector(".MuiDialogContent-root");
        const mid = c.getBoundingClientRect().top + c.clientHeight / 2;
        const node = Array.from(document.querySelectorAll(".rct-node"))
          .find((n) => n.getBoundingClientRect().top > mid && n !== window.__probeRow);
        if (!node) return JSON.stringify({ found: false });
        const b = node.querySelector(".rct-checkbox").getBoundingClientRect();
        return JSON.stringify({ found: true,
          x: Math.round(b.left + b.width / 2), y: Math.round(b.top + b.height / 2) });
      })()`));
      check(name, "a second folder is reachable", second.found, "no row below the first");
      if (second.found) await mouseClick(second.x, second.y);
      await sleep(250);
      const afterSecond = JSON.parse(await run(MEASURE));
      check(name, "picking another folder replaces the first",
        afterSecond.checkedRows === 1, `${afterSecond.checkedRows} ticked`);

      // ...and Use is genuinely clickable, not covered by anything.
      const useSpot = JSON.parse(await run(`(() => {
        const b = Array.from(document.querySelectorAll(".MuiDialogActions-root button"))
          .find((x) => /^use$/i.test((x.textContent || "").trim()));
        if (!b || b.disabled) return JSON.stringify({ ready: false });
        const r = b.getBoundingClientRect();
        const hit = document.elementFromPoint(r.left + r.width / 2, r.top + r.height / 2);
        return JSON.stringify({ ready: b.contains(hit),
          x: Math.round(r.left + r.width / 2), y: Math.round(r.top + r.height / 2) });
      })()`));
      check(name, "Use is on top and clickable", useSpot.ready, "something covers it");
      if (useSpot.ready) {
        await mouseClick(useSpot.x, useSpot.y);
        await sleep(250);
        const saved = JSON.parse(await run(`JSON.stringify(window.__saved || [])`));
        check(name, "Use hands back exactly one path", saved.length === 1,
          JSON.stringify(saved));
      }

      console.log(
        `${name.padEnd(10)} row ${before.rowTop} -> ${after.rowTop} ` +
        `| scrollTop ${before.contentScrollTop} -> ${after.contentScrollTop} ` +
        `| paper.scrollTop ${after.paperScrollTop} ` +
        `| gapBelowActions ${after.gapBelowActions} ` +
        `| active ${after.active && after.active.tag}`
      );
    }
  } finally {
    if (ws) ws.close();
    chrome.kill();
    rmSync(PAGE, { force: true });
  }

  if (failures.length) {
    console.error(`\n${failures.length} layout regression(s):`);
    failures.forEach((line) => console.error(`  - ${line}`));
    process.exit(1);
  }
  console.log("\nLayout stable at every viewport.");
};

main().catch((error) => {
  rmSync(PAGE, { force: true });
  console.error(error);
  process.exit(1);
});
